library(QAL)
expect_error <- function(expr) stopifnot(inherits(try(force(expr), silent=TRUE), "try-error"))
set.seed(2026)
d <- simulate_qal(n=400,p=8); xn <- paste0("X",1:8); grid <- c(-2,-.5,.25)
for(q in c(.25,.75)) {
 f <- qal(d,xn,"A","Y",tau=q,lambda_exponents=grid)
 stopifnot(is.finite(f$estimate),all(f$weights>0),length(f$weights)==nrow(d),abs(diff(predict(f))-f$estimate)<1e-10)
 refd <- data.frame(y=d$Y,a=d$A)
 ref <- quantreg::rq(y~a,data=refd,tau=q,weights=f$weights)
 stopifnot(abs(coef(ref)["a"]-f$estimate)<1e-8)
 xs <- scale(as.matrix(d[xn])); a <- d$A; w <- f$weights
 bal <- vapply(seq_along(xn),function(j) abs(sum(xs[a==1,j]*w[a==1])/sum(w[a==1])-sum(xs[a==0,j]*w[a==0])/sum(w[a==0])),numeric(1))
 stopifnot(max(abs(bal-f$balance$weighted))<1e-10)
 ds <- d; ds$Y <- ds$Y+10
 fs <- qal(ds,xn,"A","Y",tau=q,lambda_exponents=grid)
 stopifnot(abs(fs$estimate-f$estimate)<1e-7)
 dr <- d; names(dr)[1] <- "age in years"
 fr <- qal(dr,c("age in years",xn[-1]),"A","Y",tau=q,lambda_exponents=grid)
 stopifnot(abs(fr$estimate-f$estimate)<1e-8)
 fk <- qal(d,xn[-1],"A","Y",tau=q,known="X1",lambda_exponents=grid)
 stopifnot("X1" %in% fk$selected)
}
fbase <- qal(d,xn,"A","Y",tau=.25,lambda_exponents=grid)
tau <- .99; Y <- rep(-999,nrow(d))
fglobal <- qal(d,xn,"A","Y",tau=.25,lambda_exponents=grid)
stopifnot(abs(fbase$estimate-fglobal$estimate)<1e-10)
for(q in list(0,1,NA_real_,c(.25,.75))) expect_error(qal(d,xn,"A","Y",tau=q))
bad<-d;bad$X1[1]<-NA;expect_error(qal(bad,xn,"A","Y"))
bad<-d;bad$X1<-1;expect_error(qal(bad,xn,"A","Y"))
bad<-d;bad$X2<-bad$X1;expect_error(qal(bad,xn,"A","Y"))
bad<-d;bad$A<-1;expect_error(qal(bad,xn,"A","Y"))
expect_error(qal(d,xn,"A","Y",known="X1"))
expect_error(qal(d[1:7,],xn,"A","Y"))
expect_error(qal(d,xn,"A","Y",ps_clip=.5))
expect_error(predict(fglobal,.5))
cat("All QAL regression tests passed.\n")
